// Re-records src/sample-data.ts, the saved session behind "Replay the saved example".
// It runs the real /api/ideas pipeline once: Qloo and model fakes (forced, so the recording is stable even when they are live),
// live Channel3 and Tavily. Responses are cached on disk outside the repo so re-runs do not spend the call budgets.
// Usage: node --experimental-strip-types scripts/record-sample.ts [budget_usd]
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createApp } from '../src/app.ts';
import type { Env, StreamEvent } from '../src/types.ts';

process.loadEnvFile(new URL('../../.env.local', import.meta.url));
const FAVORITES = [
  { text: 'Hario V60' },
  { text: 'Kafka on the Shore' },
  { text: 'Nujabes' },
  { text: 'Stardew Valley' },
  { text: 'Kyoto' },
];
const BUDGET_USD = Number(process.argv[2] ?? 120);
const CACHE = '/tmp/ta-scratch/rec-cache';
const LEDGER = '/tmp/ta-scratch/ledger.jsonl';
mkdirSync(CACHE, { recursive: true });

const fetchCached = async (url: string, init?: RequestInit): Promise<Response> => {
  const key = createHash('sha256').update(`${init?.method ?? 'GET'} ${url} ${typeof init?.body === 'string' ? init.body : ''}`).digest('hex').slice(0, 24);
  const file = `${CACHE}/${key}.json`;
  if (existsSync(file)) {
    const c = JSON.parse(readFileSync(file, 'utf8'));
    return new Response(c.text, { status: c.status, headers: { 'content-type': 'application/json' } });
  }
  const res = await fetch(url, init);
  const text = await res.text();
  appendFileSync(LEDGER, JSON.stringify({ t: new Date().toISOString(), service: new URL(url).host, purpose: 'record-sample' }) + '\n');
  if (res.ok) writeFileSync(file, JSON.stringify({ status: res.status, text }));
  return new Response(text, { status: res.status, headers: { 'content-type': 'application/json' } });
};

const env: Env = {
  CHANNEL3_API_KEY: process.env.CHANNEL3_API_KEY,
  TAVILY_API_KEY: process.env.TAVILY_API_KEY,
  PAYPAL_CLIENT_ID: process.env.PAYPAL_CLIENT_ID,
  PAYPAL_CLIENT_SECRET: process.env.PAYPAL_CLIENT_SECRET,
  FORCE_MOCK: 'qloo,ai',
};
const app = createApp({ fetch: fetchCached, fast: true });
const res = await app.request(
  '/api/ideas',
  { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ favorites: FAVORITES, budget_usd: BUDGET_USD }) },
  env,
);
if (!res.ok) throw new Error(`ideas failed with ${res.status}`);
const events = (await res.text()).split('\n').filter(Boolean).map((l) => JSON.parse(l) as StreamEvent);
const err = events.find((e) => e.t === 'error');
if (err) throw new Error(`pipeline error: ${JSON.stringify(err)}`);
// the replay supplies its own meta and done events; the example session id is created at replay time
const kept = events.filter((e) => e.t !== 'meta' && e.t !== 'done');
const ideas = kept.filter((e) => e.t === 'idea').length;
const cards = kept.flatMap((e) => (e.t === 'idea' ? e.cards : [])).length;
const data = { asOf: new Date().toISOString().slice(0, 10), budget_cents: Math.round(BUDGET_USD * 100), favorites: FAVORITES, events: kept };
const out = `// Generated by scripts/record-sample.ts on ${data.asOf}. Do not edit by hand.
// A recorded session: real Channel3 product cards and Tavily links; Qloo and model answers came from the demo fakes (see README).
import type { StreamEvent } from './types.ts';

export const SAMPLE: { asOf: string; budget_cents: number; favorites: { text: string; type?: string }[]; events: StreamEvent[] } = ${JSON.stringify(data, null, 1)};
`;
writeFileSync(new URL('../src/sample-data.ts', import.meta.url), out);
console.log(`recorded ${ideas} ideas, ${cards} cards, ${kept.length} events (budget $${BUDGET_USD})`);
